"""Broadcast Diagnostics through Home Assistant: the two websocket
commands, EXECUTED against the backend's own answers.

The answers are broadcast_diagnostics_api.EXCHANGES: what the real routes
returned, with the key, over synthetic records (generated by
scripts/dev/broadcast_diagnostics_fixture.py; the last test here re-runs
the generator where the backend source is present and fails if the copy
has drifted). The
fake service below answers a request only if it is EXACTLY the path the
backend was asked for, so the client's URL is pinned as well as its
pass-through.

Pinned:
  * both commands exist, are read-only, and sit behind Home Assistant's
    administrator gate (they carry the drafts the station refused);
  * an opportunity is asked for by its public 16-hex id and nothing else:
    a break's 32-hex token, or anything shaped like a path, never leaves;
  * the answers pass through unedited -- and carry no token, no path, no
    URL and no calendar title, and the list carries no script;
  * an id the history does not hold is {ok: false, reason: "not_found"},
    and a service without the routes is {ok: false, reason: "unsupported"}:
    neither is a failure, and neither is a finding about the break.
"""

import asyncio
import importlib.util
import json
import os
import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from harness import (BACKEND_SRC, CROSS_REPO, FakeResponse, FakeTransport,  # noqa: F401
                     make_hass)

import custom_components.parlorwave_radio as integration
from broadcast_diagnostics_api import EXCHANGES

ROOT = Path(__file__).resolve().parent.parent / "custom_components" / "parlorwave_radio"
INIT = (ROOT / "__init__.py").read_text()
API = (ROOT / "api.py").read_text()
KEY = "k"                                   # the harness entry's key
CALENDAR_TITLE = "Dinner with the Hendersons"   # the backend scenario's private title
#: the list and record answers by path. The auth and bad-cursor exchanges
#: share the first page's path, and `partial:1` is a second answer to it (the
#: read ran out of budget): each is served only when a test asks for it
BY_PATH = {e["path"]: e for e in EXCHANGES
           if e["kind"] in ("list", "detail") and not e["name"].startswith("partial")}
LISTS = [e for e in EXCHANGES if e["kind"] == "list"]
DETAILS = [e for e in EXCHANGES if e["kind"] == "detail"]


class DiagTransport(FakeTransport):
    """The harness backend plus the two diagnostics routes, answered only
    for a request the backend really was asked."""

    def __init__(self, override=None, **kw):
        super().__init__(**kw)
        self.override = override or {}
        self.diag: list[dict] = []

    async def request(self, method, url, json=None, headers=None, timeout=None):
        full = "/" + url.split("//", 1)[-1].split("/", 1)[1]
        if full.startswith("/dj/diagnostics/"):
            self.diag.append({"method": method, "path": full, "headers": dict(headers or {})})
            if full in self.override:
                status, body = self.override[full]
                return FakeResponse(status, body)
            if full not in BY_PATH:
                return FakeResponse(599, {"detail": f"unrecorded request {full}"})
            e = BY_PATH[full]
            return FakeResponse(e["status"], e["body"])
        return await super().request(method, url, json=json, headers=headers, timeout=timeout)


def setup(transport):
    hass, entry = make_hass(transport)
    asyncio.run(integration.async_setup_entry(hass, entry))
    return hass


class FakeConnection:
    def __init__(self):
        self.result = None
        self.error = None

    def send_result(self, _id, result):
        self.result = result

    def send_error(self, _id, code, message):
        self.error = (code, message)


def handler_for(hass, name):
    wanted = f"parlorwave_radio/{name}"
    for handler in hass.data.get("_fake_ws_commands", []):
        if handler.ws_schema.get("type") == wanted:
            return handler
    raise AssertionError(f"{wanted} is not registered")


def call(hass, name, msg=None):
    """One command, exactly as Home Assistant invokes it: (result, error)."""
    conn = FakeConnection()
    payload = {"id": 1, "type": f"parlorwave_radio/{name}"}
    payload.update(msg or {})
    asyncio.run(handler_for(hass, name)(hass, conn, payload))
    return conn.result, conn.error


class TheCommands(unittest.TestCase):
    def test_both_are_registered_and_kept_for_administrators(self):
        hass = setup(DiagTransport())
        for name in ("broadcast_diagnostics_list", "broadcast_diagnostics_detail"):
            self.assertTrue(getattr(handler_for(hass, name), "requires_admin", False), name)

    def test_the_schema_admits_only_a_public_id_and_a_bounded_page(self):
        block = INIT[INIT.index('_command("parlorwave_radio/broadcast_diagnostics_list"'):]
        block = block[:block.index("admin=True)", block.index("broadcast_diagnostics_detail")) + 11]
        self.assertIn('vol.Required("opportunity_id"): vol.Match(r"^[0-9a-f]{16}$")', block)
        self.assertIn("vol.Range(min=1, max=200)", block)
        self.assertEqual(block.count("admin=True"), 2)

    def test_reading_writes_nothing_and_touches_no_other_route(self):
        transport = DiagTransport()
        hass = setup(transport)
        before = len(transport.calls)
        e = LISTS[0]
        result, error = call(hass, "broadcast_diagnostics_list", e["params"])
        self.assertEqual((result, error), (e["body"], None))
        result, error = call(hass, "broadcast_diagnostics_detail", DETAILS[0]["params"])
        self.assertEqual((result, error), (DETAILS[0]["body"], None))
        self.assertEqual(len(transport.calls), before, "a diagnostics read reached another route")
        self.assertEqual({c["method"] for c in transport.diag}, {"GET"})


class TheAnswersPassThrough(unittest.TestCase):
    def test_every_recorded_page_is_asked_for_by_its_exact_path_with_the_key(self):
        for e in LISTS:
            with self.subTest(e["name"]):
                transport = DiagTransport(override={e["path"]: (e["status"], e["body"])})
                hass = setup(transport)
                result, error = call(hass, "broadcast_diagnostics_list", e["params"])
                self.assertIsNone(error)
                self.assertEqual(result, e["body"])
                self.assertEqual([c["path"] for c in transport.diag], [e["path"]])
                self.assertEqual(transport.diag[0]["headers"].get("X-Api-Key"), KEY)

    def test_every_recorded_record_is_answered_as_the_backend_said(self):
        for e in DETAILS:
            with self.subTest(e["name"]):
                hass = setup(DiagTransport())
                result, error = call(hass, "broadcast_diagnostics_detail", e["params"])
                self.assertIsNone(error)
                if e["status"] == 404:
                    self.assertEqual(result, {"ok": False, "reason": "not_found"})
                else:
                    self.assertEqual(result, e["body"])

    def test_a_service_without_the_routes_is_unsupported_not_a_failure(self):
        first = LISTS[0]
        hass = setup(DiagTransport(override={first["path"]: (404, {"detail": "Not Found"})}))
        result, error = call(hass, "broadcast_diagnostics_list", first["params"])
        self.assertIsNone(error)
        self.assertEqual(result, {"ok": False, "reason": "unsupported"})

    def test_a_refused_key_and_a_bad_cursor_are_refusals_that_name_no_key(self):
        first = LISTS[0]
        no_key = next(e for e in EXCHANGES if e["name"] == "auth:wrong_key")
        hass = setup(DiagTransport(override={first["path"]: (no_key["status"], no_key["body"])}))
        _, error = call(hass, "broadcast_diagnostics_list", first["params"])
        self.assertEqual(error, ("backend", "The ParlorWave Radio service rejected the API key"))
        bad = next(e for e in EXCHANGES if e["name"] == "bad_cursor")
        self.assertEqual(bad["status"], 422)
        hass = setup(DiagTransport(override={bad["path"]: (bad["status"], bad["body"])}))
        _, error = call(hass, "broadcast_diagnostics_list",
                        {"limit": 25, "kind": "dj_break", "before": "yesterday"})
        self.assertEqual(error[0], "backend")
        self.assertIn(" answered 422: ", error[1], "not the backend's refusal of the cursor")


class OnlyAPublicIdLeaves(unittest.TestCase):
    def test_a_token_or_a_path_is_refused_before_any_request(self):
        # the shape of a break token (32 lowercase hex), built rather than
        # written out: a credential-shaped literal is what the public
        # repository's privacy check refuses, and this one is not a secret
        token = "ab" * 16
        for bad in (token, token[:16].upper(), "../../settings", "0123456789abcde",
                    "0123456789abcdef/x", "", "0123456789abcdef?x=1"):
            with self.subTest(bad):
                transport = DiagTransport()
                hass = setup(transport)
                result, error = call(hass, "broadcast_diagnostics_detail", {"opportunity_id": bad})
                self.assertIsNone(result)
                self.assertEqual(error, ("backend", "not an opportunity id"))
                self.assertEqual(transport.diag, [], "an invalid id reached the service")


class NothingPrivateCrosses(unittest.TestCase):
    """The backend scrubs; this pins that what Home Assistant forwards is
    clean too -- every answer, as the commands return it."""

    def answers(self):
        for e in EXCHANGES:
            if e["kind"] in ("list", "detail"):
                hass = setup(DiagTransport(override={e["path"]: (e["status"], e["body"])}))
                name = "broadcast_diagnostics_" + e["kind"]
                result, error = call(hass, name, e["params"])
                self.assertIsNone(error, e["name"])
                yield e, result

    def test_no_token_path_url_key_or_calendar_title(self):
        for e, result in self.answers():
            text = json.dumps(result)
            with self.subTest(e["name"]):
                self.assertIsNone(re.search(r"\b[0-9a-f]{32}\b", text), "a break token")
                for needle in (CALENDAR_TITLE, "Hendersons", "/data/", "http://", "https://",
                               "audio_path", "api_key", "X-Api-Key", "break_ref"):
                    self.assertNotIn(needle, text, needle)

    def test_the_list_carries_no_script_and_the_record_does(self):
        for e, result in self.answers():
            if e["kind"] == "list":
                for item in result["items"]:
                    self.assertFalse({"smart_dj", "aired_copy", "pipeline"} & set(item), e["name"])
                self.assertNotIn("raw_draft", json.dumps(result))
                self.assertNotIn("final_text", json.dumps(result))
        genuine = next(e for e in DETAILS if e["name"] == "detail:genuine")
        self.assertIn("went platinum in 1994", genuine["body"]["smart_dj"]["raw_draft"])
        self.assertTrue(genuine["body"]["aired_copy"]["final_text"])

    def test_a_spoken_calendar_title_arrives_masked(self):
        cal = next(e for e in DETAILS if e["name"] == "detail:calendar")["body"]
        self.assertIn("[calendar event]", cal["aired_copy"]["final_text"])
        self.assertEqual(cal["evidence"]["redactions"], ["calendar_title"])


@unittest.skipUnless(BACKEND_SRC is not None, CROSS_REPO)
class TheFixtureIsTheBackendsAnswer(unittest.TestCase):
    """The committed answers are regenerated from the real routes and
    compared byte for byte. Needs the backend's dependencies (the test
    image has them); a host without fastapi skips and says so."""

    def test_the_committed_copy_has_not_drifted(self):
        if importlib.util.find_spec("fastapi") is None:
            self.skipTest("the backend's dependencies are not installed here")
        repo = BACKEND_SRC.parent.parent
        env = dict(os.environ, PYTHONPATH=f"{BACKEND_SRC}:{BACKEND_SRC / 'tests'}",
                   PYTHONDONTWRITEBYTECODE="1")
        with tempfile.TemporaryDirectory() as base:
            env["MUSICBRAIN_BASE_DIR"] = base
            out = subprocess.run([sys.executable, "-B",
                                  str(repo / "scripts" / "dev" / "broadcast_diagnostics_fixture.py")],
                                 capture_output=True, text=True, env=env, cwd=base, timeout=300)
        self.assertEqual(out.returncode, 0, out.stderr[-2000:])
        committed = (Path(__file__).resolve().parent / "broadcast_diagnostics_api.py").read_text()
        self.assertEqual(out.stdout, committed,
                         "regenerate ha/tests/broadcast_diagnostics_api.py with "
                         "scripts/dev/broadcast_diagnostics_fixture.py")


